"""
Space AI 2.0

Rule Result

Immutable Value Object produced by a single decision rule.

A RuleResult represents the evaluation performed by an
individual rule. It is later interpreted by the
RuleEngine and the active Decision Strategy to build
the final Decision.

Compatible with:
    - Python 3.13.5
    - Ruff
    - MyPy (strict)
"""

from __future__ import annotations

# ============================================================================
# Standard Library
# ============================================================================
from dataclasses import dataclass

# ============================================================================
# Space AI - Other Engines
# ============================================================================
from ia.core.value_objects import Confidence

# ============================================================================
# Space AI - Same Package
# ============================================================================
from .enums import DecisionAction


@dataclass(
    frozen=True,
    slots=True,
)
class RuleResult:
    """
    Immutable result generated by a decision rule.

    Attributes
    ----------
    action:
        Action proposed by the evaluated rule.

    confidence:
        Confidence assigned by the rule.

    passed:
        Indicates whether the rule conditions were
        successfully satisfied.

    reason:
        Human-readable explanation describing the result
        generated by the rule.
    """

    action: DecisionAction

    confidence: Confidence

    passed: bool

    reason: str


__all__ = [
    "RuleResult",
]

