"""
Space AI 2.0

Inference Result

Immutable result produced by the inference pipeline.

This model encapsulates every artifact generated during a
single inference cycle. It represents the output of the
Runtime inference stage and serves as the input for the
learning stage.

Compatible with:
    - Python 3.13.5
    - Ruff
    - Black
    - isort
    - MyPy (strict)
"""

from __future__ import annotations

from dataclasses import dataclass

from ia.decision_engine.decision import Decision
from ia.signal_engine.result import SignalResult
from predictor.prediction import Prediction
from state_engine.models.classification_result import (
    ClassificationResult,
)
from state_engine.state_history import StateHistory


@dataclass(
    frozen=True,
    slots=True,
    kw_only=True,
)
class InferenceResult:
    """
    Immutable output of one inference cycle.

    Attributes
    ----------
    classification:
        Semantic classification generated by the State Engine.

    history:
        Updated immutable StateHistory.

    prediction:
        Prediction generated by the Predictor Engine.

    decision:
        Decision generated by the Decision Engine.

    signal_result:
        Final SignalResult generated by the Signal Engine.
    """

    classification: ClassificationResult

    history: StateHistory

    prediction: Prediction

    decision: Decision

    signal_result: SignalResult


__all__ = [
    "InferenceResult",
]
