"""
Space AI 2.0

Prediction History

Immutable history of predictions generated by the
Predictor Engine.
"""

from __future__ import annotations

from dataclasses import dataclass

from predictor.prediction import Prediction


@dataclass(
    frozen=True,
    slots=True,
)
class PredictionHistory:
    """
    Immutable aggregate containing every generated
    Prediction.

    This object contains no business logic.

    New histories are always produced by the
    Predictor Engine.
    """

    predictions: tuple[Prediction, ...] = ()


__all__ = [
    "PredictionHistory",
]

