"""
Space AI 2.0

Prediction

Immutable prediction produced by the Predictor Engine.

A Prediction represents the inferred next system state
together with its associated probability and confidence.
"""

from __future__ import annotations

from dataclasses import dataclass

from predictor.confidence import Confidence
from predictor.probability import Probability
from state_engine.state_labels import StateLabels


@dataclass(
    frozen=True,
    slots=True,
)
class Prediction:
    """
    Immutable prediction generated by a prediction strategy.

    This value object represents the predicted next state
    together with the probability assigned by the strategy
    and the confidence of the prediction.
    """

    labels: StateLabels

    probability: Probability

    confidence: Confidence


__all__ = [
    "Prediction",
]

